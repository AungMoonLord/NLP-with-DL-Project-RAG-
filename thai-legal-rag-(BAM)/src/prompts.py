def format_context(retrieved) -> str:
    """แปลง chunk เป็นบล็อกข้อความ พร้อม label [S1..Sn] และ citation"""
    blocks = []
    for i, r in enumerate(retrieved, start=1):
        c = r.chunk
        blocks.append(f"[S{i}] แหล่งที่มา: {c.citation}\n{c.text}")
    return "\n\n---\n\n".join(blocks)


